CREATE PROCEDURE [BVQ_BACKOFFICE].[LimpiarPAIReforma]
    @i_periodo  VARCHAR(100),
    @i_reforma  VARCHAR(100) = NULL,
    @i_lga_id   INT = NULL
AS
BEGIN
    SET NOCOUNT ON;

    SET @i_reforma = NULLIF(LTRIM(RTRIM(@i_reforma)), '');

    DECLARE @PAI_ID INT;

    -- NULL-safe: el PAI original tiene PAI_REFORMA = NULL.
    SELECT @PAI_ID = PAI_ID FROM BVQ_BACKOFFICE.PAI_GENERAL
    WHERE PAI_PERIODO = @i_periodo
      AND (PAI_REFORMA = @i_reforma OR (PAI_REFORMA IS NULL AND @i_reforma IS NULL));

    IF @PAI_ID IS NULL
        RETURN;

    DELETE pm
    FROM BVQ_BACKOFFICE.PAI_MONTO pm
    INNER JOIN BVQ_BACKOFFICE.PAI_TABLA tab ON tab.TAB_ID = pm.TAB_ID
    WHERE tab.PAI_ID = @PAI_ID;

    DELETE tip
    FROM BVQ_BACKOFFICE.PAI_TIPO_INVERSION tip
    INNER JOIN BVQ_BACKOFFICE.PAI_TABLA tab ON tab.TAB_ID = tip.TAB_ID
    WHERE tab.PAI_ID = @PAI_ID;

    DELETE fop
    FROM BVQ_BACKOFFICE.PAI_FONDO fop
    INNER JOIN BVQ_BACKOFFICE.PAI_TABLA tab ON tab.TAB_ID = fop.TAB_ID
    WHERE tab.PAI_ID = @PAI_ID;

    DELETE FROM BVQ_BACKOFFICE.PAI_TABLA WHERE PAI_ID = @PAI_ID;
END
