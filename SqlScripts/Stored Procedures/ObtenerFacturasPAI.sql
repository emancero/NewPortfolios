CREATE PROCEDURE [BVQ_BACKOFFICE].[ObtenerFacturasPAI]
    @i_lga_id INT
AS
BEGIN
    SET NOCOUNT ON;

    SELECT f.PAF_ID, f.PFC_ID, c.PFC_NOMBRE, f.PAF_FECHA_FACTURA, f.PAF_FECHA_CORTE, f.PAF_MONTO
    FROM BVQ_BACKOFFICE.PAI_FACTURA f
    INNER JOIN BVQ_BACKOFFICE.PAI_FACTURA_CUSTODIO c ON c.PFC_ID = f.PFC_ID
    ORDER BY f.PAF_FECHA_FACTURA DESC, f.PAF_ID DESC;
END
