create PROCEDURE [BVQ_BACKOFFICE].[ObtenerFondosTitulosPAI]
    @i_anio    VARCHAR(100),
    @i_lga_id  INT = NULL
AS
-- Celdas fondo × tipo de inversión de la misma tabla (PAI_TABLA) del PAI del año;
-- IDs de PAI_CODIGO_PRESTABLECIDO (por código), como se guardan en PAI_FACTURA_FONDO.
SELECT
	pf.PCP_ID AS F_ID,
	pp.POR_ID,
	pf.PCP_NOMBRE AS F_NOMBRE,
	MIN(fop.FOP_ORDEN) AS F_ORDEN,
	pt.PCP_ID AS T_ID,
	pt.PCP_NOMBRE AS T_NOMBRE,
	MIN(tab.TAB_ORDEN * 1000 + tip.TIP_ORDEN) AS T_ORDEN,
	CAST(0 AS FLOAT) AS MONTO
FROM [BVQ_BACKOFFICE].[PAI_GENERAL] pg
	INNER JOIN [BVQ_BACKOFFICE].[PAI_TABLA] tab ON tab.PAI_ID = pg.PAI_ID
	INNER JOIN [BVQ_BACKOFFICE].[PAI_FONDO] fop ON fop.TAB_ID = tab.TAB_ID
	INNER JOIN [BVQ_BACKOFFICE].[PAI_TIPO_INVERSION] tip ON tip.TAB_ID = tab.TAB_ID
	INNER JOIN [BVQ_BACKOFFICE].[PAI_CODIGO_PRESTABLECIDO] pf ON pf.PCP_TIPO = 'FONDO' AND pf.PCP_CODIGO = fop.FOP_CODIGO
	INNER JOIN [BVQ_BACKOFFICE].[PAI_CODIGO_PRESTABLECIDO] pt ON pt.PCP_TIPO = 'TIPO_INVERSION' AND pt.PCP_CODIGO = tip.TIP_CODIGO
	LEFT JOIN [BVQ_BACKOFFICE].[PAI_CODIGO_PORTAFOLIO] pp ON pp.PCP_ID = pf.PCP_ID
WHERE pg.PAI_PERIODO = @i_anio
GROUP BY pf.PCP_ID, pp.POR_ID, pf.PCP_NOMBRE, pt.PCP_ID, pt.PCP_NOMBRE
ORDER BY F_ORDEN, T_ORDEN
GO


