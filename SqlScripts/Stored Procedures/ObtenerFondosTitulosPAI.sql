create PROCEDURE [BVQ_BACKOFFICE].[ObtenerFondosTitulosPAI]
    @i_lga_id  INT
AS
SELECT 
	ff.PCP_ID AS F_ID,
	ff.POR_ID,
	ff.PCP_TIPO AS F_TIPO,
	ff.PCP_NOMBRE AS F_NOMBRE,
	ff.PCP_CODIGO AS F_CODIGO,
	tt.PCP_ID AS T_ID,
	tt.PCP_TIPO AS T_TIPO,
	tt.PCP_NOMBRE AS T_NOMBRE,
	tt.PCP_CODIGO AS T_CODIGO,
	CAST(0 AS MONEY) AS MONTO
FROM
	(SELECT c.PCP_ID, c.PCP_TIPO, c.PCP_NOMBRE, c.PCP_CODIGO, p.POR_ID
	FROM [BVQ_BACKOFFICE].[PAI_CODIGO_PRESTABLECIDO] c
	LEFT JOIN [BVQ_BACKOFFICE].[PAI_CODIGO_PORTAFOLIO] p ON c.PCP_ID = p.PCP_ID
	WHERE PCP_TIPO = 'FONDO' AND p.POR_ID IS NOT NULL) ff
	LEFT JOIN 
		(SELECT c.PCP_ID, c.PCP_TIPO, c.PCP_NOMBRE, c.PCP_CODIGO
		FROM [BVQ_BACKOFFICE].[PAI_CODIGO_PRESTABLECIDO] c
		WHERE PCP_TIPO = 'TIPO_INVERSION') tt
	ON 1 = 1
ORDER BY ff.PCP_ID, tt.PCP_ID
GO


